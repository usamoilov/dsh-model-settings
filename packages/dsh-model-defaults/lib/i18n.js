export const MESSAGES = { en, ru, zh }

/** Language of a request: `ru`/`zh`/`en` from the page's DSH locale, else English. */
export function localeOf(request) {
  const raw = String(request?.headers?.get?.('x-dsh-locale') || '').toLowerCase()
  const primary = raw.split(/[-_]/)[0]
  return Object.hasOwn(MESSAGES, primary) ? primary : 'en'
}

/** Translator for one language; missing keys fall back to English, then to the key. */
export function translator(locale) {
  const dict = MESSAGES[locale] || en
  return (key, params) => {
    const template = dict[key] ?? en[key] ?? key
    if (!params) return template
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match))
  }
}

/** An error the page can show translated: carries a message key and its params. */
export function failure(status, key, params) {
  return Object.assign(new Error(translator('en')(key, params)), { status, key, params })
}
